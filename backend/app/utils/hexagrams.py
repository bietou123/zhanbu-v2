def _build_index() -> dict[tuple[str, str], dict]:
    out = {}
    for no, name, upper, lower, yao_ci in HEXAGRAMS_64:
        out[(upper, lower)] = {
            "no": no, "name": name,
            "upper": upper, "lower": lower,
            "judgement": yao_ci,
        }
    return out


HEXAGRAM_BY_TRIGRAMS = _build_index()


@dataclass
class Hexagram:
    """6 爻自下而上：yao[0]=初爻 ... yao[5]=上爻；1=阳 0=阴。"""
    yao: tuple[int, int, int, int, int, int]

    @property
    def upper(self) -> str:
        # 上卦：4、5、6 爻 = 索引 3,4,5 → (上,中,下) 即 (yao[5], yao[4], yao[3])
        return BIN_TO_TRIGRAM[(self.yao[5], self.yao[4], self.yao[3])]

    @property
    def lower(self) -> str:
        return BIN_TO_TRIGRAM[(self.yao[2], self.yao[1], self.yao[0])]

    def info(self) -> dict:
        return HEXAGRAM_BY_TRIGRAMS[(self.upper, self.lower)]

    def to_dict(self) -> dict:
        i = self.info()
        return {
            **i,
            "yao_bottom_up": list(self.yao),
            "upper_trigram_info": TRIGRAMS[self.upper],
            "lower_trigram_info": TRIGRAMS[self.lower],
        }


def hexagram_from_yao(yao: list[int]) -> Hexagram:
    if len(yao) != 6 or any(y not in (0, 1) for y in yao):
        raise ValueError("yao 必须是 6 个 0/1 组成的列表（自下而上）")
    return Hexagram(tuple(yao))  # type: ignore[arg-type]


def hu_gua(h: Hexagram) -> Hexagram:
    """互卦：2,3,4 爻为下卦，3,4,5 爻为上卦。"""
    new = (h.yao[1], h.yao[2], h.yao[3], h.yao[2], h.yao[3], h.yao[4])
    return Hexagram(new)


def cuo_gua(h: Hexagram) -> Hexagram:
    """错卦：每爻取反。"""
    return Hexagram(tuple(1 - y for y in h.yao))  # type: ignore[arg-type]


def zong_gua(h: Hexagram) -> Hexagram:
    """综卦：上下颠倒。"""
    return Hexagram(tuple(reversed(h.yao)))  # type: ignore[arg-type]


def bian_gua(h: Hexagram, changing_yao_idx: list[int]) -> Hexagram:
    """变卦：指定的动爻取反 (0=初爻 ... 5=上爻)。"""
    new = list(h.yao)
    for i in changing_yao_idx:
        new[i] = 1 - new[i]
    return Hexagram(tuple(new))  # type: ignore[arg-type]
